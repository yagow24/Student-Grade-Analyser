def student_details():

    student_name = input("Enter the name of the student: ")
    student_rollno = input("Enter the roll number of the student: ").strip()

    return student_name, student_rollno



def get_subjects():

    while True:
        try:
            subject_count = int(input("Enter the number of subjects: "))

            if subject_count <= 0:
                print("Enter at least 1 subject!")
                continue

            break

        except ValueError:
            print("Please enter a valid number!")

    subject_list = []
    subject_marks = []

    for i in range(subject_count):

        subject_name = input("Enter the subject: ")

        while True:
            try:
                mark = int(input("Enter the marks: "))

                if mark < 0 or mark > 100:
                    print("Invalid marks! Enter between 0 to 100.")
                    continue

                break

            except ValueError:
                print("Please enter a valid number!")

        subject_list.append(subject_name)
        subject_marks.append(mark)

    return subject_list, subject_marks




def calculate_result(subject_marks):

    total = sum(subject_marks)
    average = total / len(subject_marks)

    if average >= 90:
        grade = "A+"
    elif average >= 80:
        grade = "A"
    elif average >= 70:
        grade = "B"
    elif average >= 60:
        grade = "C"
    elif average >= 50:
        grade = "D"
    else:
        grade = "F"

    if grade != "F":
        result = "Pass"
    else:
        result = "Fail"

    return total, average, grade, result


def display_result(name, rollno, subjects, marks,
                   total, average, grade, result):

    print("\n======= Student Marks Analyzed =======")

    print("Student Name:", name)
    print("Student Roll No:", rollno)

    print("\nSubject-wise Marks:")

    for i in range(len(subjects)):
        print(f"{subjects[i]}: {marks[i]}")

    print("\nTotal:", total)
    print("Average:", round(average, 2))
    print("Grade:", grade)
    print("Result:", result)


def store_student_data(name, rollno, subjects, marks,
                       total, average, grade, result):

  student = {
    "name": name,
    "rollno": rollno,
    "subjects": subjects,
    "marks": marks,
    "total": total,
    "average": average,
    "grade": grade,
    "result": result
  }

  return student

students = []



def add_student():

    name, rollno = student_details()

    while True:
        duplicate = False

        for student in students:
            if student["rollno"] == rollno:
                duplicate = True
                break

        if duplicate:
            print("Roll number already exists!")
            rollno = input("Enter a different roll number: ").strip()
        else:
            break

    subjects, marks = get_subjects()

    total, average, grade, result = calculate_result(marks)

    display_result(
        name, rollno, subjects, marks,
        total, average, grade, result
    )

    student = store_student_data(
        name, rollno, subjects, marks,
        total, average, grade, result
    )

    students.append(student)




def view_all_reports():
  if len(students) == 0:
    print("No students found!")
  else:
    for student in students:

      display_result(
          student["name"],
          student["rollno"],
          student["subjects"],
          student["marks"],
          student["total"],
          student["average"],
          student["grade"],
          student["result"]

      )

def class_summary():

  if len(students)==0:
    print("no students found!")
  else :
    topper = max(
        students,
        key = lambda student: student["average"]
    )

    print("\n=======CLASS SUMMARY=======")
    print("Class Topper:",topper["name"])
    print("topper average:",topper["average"])

    lowest = min(
        students,
        key = lambda student: student["average"]

    )

    print("Lowest Scorer:",lowest["name"])
    print("Lowest Average:", lowest["average"])

    class_average = sum(
        student["average"] for student in students)/len(students)

    print("class average:",round(class_average,2))



    pass_count = 0
    fail_count = 0
    for student in students:
      if student["result"] == "Pass":
        pass_count += 1
      else:
        fail_count += 1

    pass_percent = (pass_count/len(students))*100
    fail_percent =(fail_count/len(students))*100

    print("pass count:",pass_count)
    print("fail count:",fail_count)

    print("pass percentage:",round(pass_percent,2),"%")
    print("fail percentage:",round(fail_percent,2),"%")

while True:
  print("\n======STUDENT GRADE ANALAYSER=========")

  print("1. Add Student")
